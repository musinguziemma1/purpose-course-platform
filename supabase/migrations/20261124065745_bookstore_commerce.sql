create table if not exists public.store_books (
  id integer generated by default as identity primary key,
  slug varchar(96) not null unique,
  sku varchar(48) not null unique,
  isbn13 varchar(13) unique,
  title varchar(220) not null,
  subtitle varchar(240),
  author_name varchar(180) not null,
  short_description varchar(500) not null,
  description text not null,
  category varchar(80) not null,
  format varchar(24) not null default 'paperback',
  language varchar(48) not null default 'English',
  page_count integer not null default 0,
  price_ugx integer not null,
  compare_at_price_ugx integer,
  inventory_count integer not null default 0,
  low_stock_threshold integer not null default 5,
  cover_image_url text,
  cover_alt varchar(240) not null,
  cover_tone varchar(24) not null default 'navy',
  status varchar(24) not null default 'draft',
  is_featured boolean not null default false,
  is_new boolean not null default false,
  rating_tenths integer not null default 0,
  review_count integer not null default 0,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint store_books_slug_check check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint store_books_sku_check check (sku ~ '^[A-Z0-9][A-Z0-9-]{2,47}$'),
  constraint store_books_isbn_check check (isbn13 is null or isbn13 ~ '^[0-9]{13}$'),
  constraint store_books_format_check check (format in ('paperback', 'hardcover', 'workbook')),
  constraint store_books_status_check check (status in ('draft', 'active', 'archived')),
  constraint store_books_cover_tone_check check (cover_tone in ('navy', 'source', 'potential', 'destiny', 'gold', 'terracotta')),
  constraint store_books_page_count_check check (page_count >= 0),
  constraint store_books_price_check check (price_ugx >= 0 and (compare_at_price_ugx is null or compare_at_price_ugx >= price_ugx)),
  constraint store_books_inventory_check check (inventory_count >= 0 and low_stock_threshold >= 0),
  constraint store_books_rating_check check (rating_tenths between 0 and 50 and review_count >= 0)
);

create index if not exists store_books_active_category_idx
  on public.store_books (category, title)
  where status = 'active';
create index if not exists store_books_featured_idx
  on public.store_books (is_featured, published_at desc)
  where status = 'active';

create table if not exists public.store_orders (
  id uuid primary key default gen_random_uuid(),
  order_number varchar(32) not null unique,
  profile_id uuid references public.profiles(id) on delete set null,
  customer_name varchar(160) not null,
  email varchar(255) not null,
  phone varchar(32) not null,
  delivery_method varchar(32) not null,
  payment_method varchar(32) not null,
  address_line varchar(300),
  city varchar(100),
  country varchar(80) not null default 'Uganda',
  notes varchar(1000),
  currency char(3) not null default 'UGX',
  subtotal_ugx integer not null,
  delivery_ugx integer not null default 0,
  total_ugx integer not null,
  status varchar(32) not null default 'placed',
  payment_status varchar(24) not null default 'pending',
  rate_key varchar(64) not null,
  version integer not null default 0,
  placed_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz,
  cancelled_at timestamptz,
  constraint store_orders_email_check check (email = lower(email)),
  constraint store_orders_delivery_check check (delivery_method in ('pickup', 'kampala_delivery', 'uganda_delivery')),
  constraint store_orders_payment_method_check check (payment_method in ('pay_on_delivery', 'pay_on_pickup')),
  constraint store_orders_payment_delivery_match_check check (
    (delivery_method = 'pickup' and payment_method = 'pay_on_pickup') or
    (delivery_method <> 'pickup' and payment_method = 'pay_on_delivery')
  ),
  constraint store_orders_status_check check (status in ('placed', 'confirmed', 'packing', 'dispatched', 'ready_for_pickup', 'completed', 'cancelled')),
  constraint store_orders_payment_status_check check (payment_status in ('pending', 'paid', 'refunded')),
  constraint store_orders_money_check check (subtotal_ugx >= 0 and delivery_ugx >= 0 and total_ugx = subtotal_ugx + delivery_ugx),
  constraint store_orders_version_check check (version >= 0)
);

create index if not exists store_orders_profile_created_idx on public.store_orders (profile_id, placed_at desc);
create index if not exists store_orders_email_created_idx on public.store_orders (email, placed_at desc);
create index if not exists store_orders_status_created_idx on public.store_orders (status, placed_at desc);
create index if not exists store_orders_rate_created_idx on public.store_orders (rate_key, placed_at desc);

create table if not exists public.store_order_items (
  id integer generated by default as identity primary key,
  order_id uuid not null references public.store_orders(id) on delete cascade,
  book_id integer references public.store_books(id) on delete set null,
  sku varchar(48) not null,
  title varchar(220) not null,
  author_name varchar(180) not null,
  format varchar(24) not null,
  unit_price_ugx integer not null,
  quantity integer not null,
  line_total_ugx integer not null,
  constraint store_order_items_quantity_check check (quantity between 1 and 25),
  constraint store_order_items_money_check check (unit_price_ugx >= 0 and line_total_ugx = unit_price_ugx * quantity)
);

create index if not exists store_order_items_order_idx on public.store_order_items (order_id);
create index if not exists store_order_items_book_idx on public.store_order_items (book_id);

alter table public.store_books enable row level security;
alter table public.store_orders enable row level security;
alter table public.store_order_items enable row level security;

revoke all on table public.store_books, public.store_orders, public.store_order_items from public, anon, authenticated;
revoke all on sequence public.store_books_id_seq, public.store_order_items_id_seq from public, anon, authenticated;
grant select, insert, update, delete on table public.store_books, public.store_orders, public.store_order_items to purpose_app;
grant usage, select on sequence public.store_books_id_seq, public.store_order_items_id_seq to purpose_app;

create policy store_books_backend_access on public.store_books for all to purpose_app using (true) with check (true);
create policy store_orders_backend_access on public.store_orders for all to purpose_app using (true) with check (true);
create policy store_order_items_backend_access on public.store_order_items for all to purpose_app using (true) with check (true);

