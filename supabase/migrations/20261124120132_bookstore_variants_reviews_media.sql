create table if not exists public.store_book_variants (
  id integer generated by default as identity primary key,
  book_id integer not null references public.store_books(id) on delete cascade,
  code varchar(24) not null,
  label varchar(80) not null,
  delivery_kind varchar(16) not null,
  price_ugx integer not null,
  compare_at_price_ugx integer,
  inventory_count integer not null default 0,
  download_media_id uuid references public.media_assets(id) on delete restrict,
  is_active boolean not null default false,
  is_default boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint store_book_variants_book_code_unique unique (book_id, code),
  constraint store_book_variants_code_check check (code in ('digital_pdf', 'paperback', 'hardcover')),
  constraint store_book_variants_delivery_check check (
    (code = 'digital_pdf' and delivery_kind = 'digital') or
    (code in ('paperback', 'hardcover') and delivery_kind = 'physical')
  ),
  constraint store_book_variants_price_check check (price_ugx >= 0 and (compare_at_price_ugx is null or compare_at_price_ugx >= price_ugx)),
  constraint store_book_variants_inventory_check check (inventory_count >= 0),
  constraint store_book_variants_download_check check (
    (delivery_kind = 'physical' and download_media_id is null) or
    (delivery_kind = 'digital' and (not is_active or download_media_id is not null))
  )
);

create index if not exists store_book_variants_book_active_idx
  on public.store_book_variants (book_id, sort_order, id)
  where is_active;
create index if not exists store_book_variants_download_media_idx
  on public.store_book_variants (download_media_id)
  where download_media_id is not null;

