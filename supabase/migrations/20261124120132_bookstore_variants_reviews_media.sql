create table if not exists public.store_reviews (
  id uuid primary key default gen_random_uuid(),
  book_id integer not null references public.store_books(id) on delete cascade,
  profile_id uuid references public.profiles(id) on delete set null,
  order_item_id integer references public.store_order_items(id) on delete set null,
  reviewer_name varchar(160) not null,
  reviewer_email varchar(255),
  rating integer not null,
  title varchar(180),
  body varchar(3000) not null,
  status varchar(24) not null default 'pending',
  is_verified_purchase boolean not null default false,
  rate_key varchar(64) not null,
  version integer not null default 0,
  submitted_at timestamptz not null default now(),
  moderated_at timestamptz,
  moderated_by_id uuid references public.profiles(id) on delete set null,
  constraint store_reviews_order_item_unique unique (order_item_id),
  constraint store_reviews_email_check check (reviewer_email is null or reviewer_email = lower(reviewer_email)),
  constraint store_reviews_rating_check check (rating between 1 and 5),
  constraint store_reviews_status_check check (status in ('pending', 'approved', 'rejected')),
  constraint store_reviews_version_check check (version >= 0)
);

create unique index if not exists store_reviews_book_profile_unique
